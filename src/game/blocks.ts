export type BlockId = (typeof BLOCK)[keyof typeof BLOCK];

export interface BlockDef {
  readonly id: BlockId;
  readonly name: string;
  /** Linear-space RGB, 0-1. Baked straight into vertex colours. */
  readonly color: readonly [number, number, number];
  /** The original sRGB hex, for UI chips that must match the block on screen. */
  readonly hex: string;
  readonly solid: boolean;
  /** Breaks light through it — glass still culls faces against itself. */
  readonly transparent: boolean;
  /** Infinity means unbreakable. Feeds `miningTimeMs`. */
  readonly hardness: number;
  /** What hand-mining this block yields, if anything. */
  readonly drop: RawResource | null;
  /** How much per-voxel colour noise to apply. Ore veins stay crisper. */
  readonly jitter: number;
  /** Self-lit blocks ignore ambient occlusion and read as light sources. */
  readonly emissive: number;
}

/**
 * sRGB -> linear.
 *
 * The renderer outputs sRGB and treats vertex colours as linear, so palette
 * values written as web hex have to be converted or every surface comes out
 * noticeably washed out and flat. Doing it once at module load costs nothing.
 */
function srgbToLinear(channel: number): number {
  return channel <= 0.04045
    ? channel / 12.92
    : Math.pow((channel + 0.055) / 1.055, 2.4);
}

function hex(value: string): readonly [number, number, number] {
  const n = parseInt(value.replace("#", ""), 16);
  return [
    srgbToLinear(((n >> 16) & 255) / 255),
    srgbToLinear(((n >> 8) & 255) / 255),
    srgbToLinear((n & 255) / 255),
  ];
}

function def(
  id: BlockId,
  name: string,
  color: string,
  options: Partial<Omit<BlockDef, "id" | "name" | "color">> = {}
): BlockDef {
  return {
    id,
    name,
    color: hex(color),
    hex: color,
    solid: true,
    transparent: false,
    hardness: 1,
    drop: null,
    jitter: 0.06,
    emissive: 0,
    ...options,
  };
}

