import type { RawResource } from "@/sim/types";

/**
 * The block registry.
 *
 * Ids are a `Uint8Array` wire format for the world, so they are append-only.
 * Colours live here rather than in a texture atlas: STRATA is untextured by
 * design — form, ambient occlusion and per-voxel colour jitter carry the look,
 * which keeps the whole world one draw-call-friendly vertex-coloured mesh set
 * and loads instantly with no image assets at all.
 */

