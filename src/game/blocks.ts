/** Fast lookup tables — the mesher touches these once per face, per voxel. */
export const IS_SOLID = new Uint8Array(256);
export const IS_ORE = new Uint8Array(256);
export const IS_TRANSPARENT = new Uint8Array(256);
export const EMISSIVE = new Float32Array(256);
export const JITTER = new Float32Array(256);
export const COLOR_R = new Float32Array(256);
export const COLOR_G = new Float32Array(256);
export const COLOR_B = new Float32Array(256);

for (const block of Object.values(BLOCKS)) {
  IS_SOLID[block.id] = block.solid ? 1 : 0;
  IS_ORE[block.id] = block.drop !== null ? 1 : 0;
  IS_TRANSPARENT[block.id] = block.transparent ? 1 : 0;
  EMISSIVE[block.id] = block.emissive;
  JITTER[block.id] = block.jitter;
  COLOR_R[block.id] = block.color[0];
  COLOR_G[block.id] = block.color[1];
  COLOR_B[block.id] = block.color[2];
}

