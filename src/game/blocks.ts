export function blockDef(id: number): BlockDef {
  return BLOCKS[id] ?? BLOCKS[BLOCK.STONE];
}

export function isOre(id: number): boolean {
  return blockDef(id).drop !== null;
}

/** Hex string for UI chips that need to match a block exactly. */
export function blockHex(id: number): string {
  return blockDef(id).hex;
}
